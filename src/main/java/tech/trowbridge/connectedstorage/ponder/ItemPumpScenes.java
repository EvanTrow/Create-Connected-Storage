package tech.trowbridge.connectedstorage.ponder;

import com.simibubi.create.foundation.ponder.CreateSceneBuilder;

import net.createmod.ponder.api.PonderPalette;
import net.createmod.ponder.api.scene.SceneBuilder;
import net.createmod.ponder.api.scene.SceneBuildingUtil;
import net.createmod.ponder.api.scene.Selection;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.world.level.block.state.BlockState;
import tech.trowbridge.connectedstorage.content.ItemPipeBlock;
import tech.trowbridge.connectedstorage.content.LinkSide;
import tech.trowbridge.connectedstorage.index.AddonBlocks;

/**
 * Schematic: assets/connectedstorage/ponder/item_pump.nbt, generated by tools/gen_ponder.py.
 * <pre>
 *   z:        2      3      4      5      6      7      8      9
 *   x=4 y=1   vault  pipe   pipe   vault  pump   vault
 *   x=5 y=1                               cog    shaft  shaft  small cog
 *   x=4 y=0                                                    large cog
 * </pre>
 * The storage line runs front to back; the drive comes in off the back edge of the base plate, where a
 * large cog, level with the plate, turns a small cog on the pump's shaft.
 */
public class ItemPumpScenes {

    public static void linking(SceneBuilder builder, SceneBuildingUtil util) {
        CreateSceneBuilder scene = new CreateSceneBuilder(builder);
        scene.title("item_pump", "Connecting Storage with Item Pumps");
        scene.configureBasePlate(0, 0, 9);
        scene.showBasePlate();
        scene.idle(10);

        BlockPos vaultA = util.grid().at(4, 1, 7);
        BlockPos pump = util.grid().at(4, 1, 6);
        BlockPos vaultB = util.grid().at(4, 1, 5);
        BlockPos middlePipe = util.grid().at(4, 1, 4);
        BlockPos farPipe = util.grid().at(4, 1, 3);
        BlockPos vaultC = util.grid().at(4, 1, 2);
        BlockPos cog = util.grid().at(5, 1, 6);
        // Shaft from the pump's cog back off the plate, ending in a small cog...
        Selection driveShaft = util.select().fromTo(5, 1, 7, 5, 1, 9);
        // ...turned by a large cog sitting level with the plate, just off its back edge.
        Selection largeCog = util.select().position(4, 0, 9);
        Selection pumpSelection = util.select().position(pump);

        // Two separate vaults.
        scene.world().showSection(util.select().position(vaultA), Direction.DOWN);
        scene.idle(5);
        scene.world().showSection(util.select().position(vaultB), Direction.DOWN);
        scene.idle(15);
        scene.overlay().showText(60)
                .text("Item Vaults and Item Silos normally keep their items to themselves")
                .pointAt(util.vector().topOf(vaultA))
                .placeNearTarget();
        scene.idle(70);

        // The pump links them.
        scene.world().showSection(pumpSelection, Direction.DOWN);
        scene.idle(15);
        scene.overlay().showText(70)
                .text("An Item Pump links the storages on both of its ends into one shared inventory")
                .attachKeyFrame()
                .pointAt(util.vector().topOf(pump))
                .placeNearTarget();
        scene.idle(80);

        // It needs rotation.
        scene.world().showSection(largeCog, Direction.DOWN);
        scene.idle(5);
        scene.world().showSection(util.select().position(cog).add(driveShaft), Direction.DOWN);
        scene.idle(10);
        setSpeed(scene, util, largeCog, driveShaft, cog, pumpSelection, 64);
        scene.idle(10);
        scene.overlay().showText(80)
                .text("It needs rotation: drive it with a cogwheel at 16 RPM or faster")
                .attachKeyFrame()
                .pointAt(util.vector().topOf(cog))
                .placeNearTarget();
        scene.idle(90);

        Object linked = new Object();
        scene.overlay().showOutline(PonderPalette.GREEN, linked,
                util.select().position(vaultA).add(util.select().position(vaultB)), 80);
        scene.overlay().showText(80)
                .text("Funnels, chutes and packagers on either storage can now reach the items in both")
                .colored(PonderPalette.GREEN)
                .attachKeyFrame()
                .pointAt(util.vector().topOf(vaultB))
                .placeNearTarget();
        scene.idle(90);

        // Pipes carry the link further.
        scene.world().hideSection(util.select().position(vaultB), Direction.UP);
        scene.idle(15);
        scene.world().setBlock(vaultB, pipe(), false);
        // Loading the schematic connected the next pipe to the vault that stood here (drawing a vault flange);
        // the swap doesn't update neighbours, so reconnect it to the new pipe by hand.
        scene.world().setBlock(middlePipe, pipe(), false);
        scene.world().showSection(util.select().fromTo(4, 1, 3, 4, 1, 5), Direction.DOWN);
        scene.idle(5);
        scene.world().showSection(util.select().position(vaultC), Direction.DOWN);
        scene.idle(15);
        scene.overlay().showText(90)
                .text("Item Pipes carry the link further. A pump reaches 1 pipe block for every 16 RPM, up to 16 blocks")
                .attachKeyFrame()
                .pointAt(util.vector().topOf(middlePipe))
                .placeNearTarget();
        scene.idle(100);

        scene.overlay().showOutline(PonderPalette.GREEN, linked,
                util.select().position(vaultA).add(util.select().position(vaultC)), 60);
        scene.idle(70);

        // Too slow: the far vault drops out.
        setSpeed(scene, util, largeCog, driveShaft, cog, pumpSelection, 32);
        scene.idle(10);
        scene.overlay().showOutline(PonderPalette.RED, linked,
                util.select().position(farPipe).add(util.select().position(vaultC)), 80);
        scene.overlay().showText(80)
                .text("At 32 RPM it only reaches 2 pipe blocks, so the far vault is left out")
                .colored(PonderPalette.RED)
                .attachKeyFrame()
                .pointAt(util.vector().topOf(vaultC))
                .placeNearTarget();
        scene.idle(90);

        setSpeed(scene, util, largeCog, driveShaft, cog, pumpSelection, 64);
        scene.idle(10);
        scene.overlay().showText(80)
                .text("Speed it up, or add another running Item Pump along the line, to reach further")
                .attachKeyFrame()
                .pointAt(util.vector().topOf(pump))
                .placeNearTarget();
        scene.idle(90);
    }

    /** Sets the whole drive so the pump turns at {@code rpm}. */
    private static void setSpeed(CreateSceneBuilder scene, SceneBuildingUtil util, Selection largeCog,
            Selection driveShaft, BlockPos cog, Selection pump, float rpm) {
        // Meshing cogs turn the opposite way; a small cog driven by a large one turns twice as fast.
        scene.world().setKineticSpeed(pump, rpm);
        scene.world().setKineticSpeed(util.select().position(cog), -rpm);
        scene.world().setKineticSpeed(driveShaft, -rpm);
        scene.world().setKineticSpeed(largeCog, rpm / 2);
    }

    private static BlockState pipe() {
        return AddonBlocks.ITEM_PIPE.get().defaultBlockState()
                .setValue(ItemPipeBlock.NORTH, LinkSide.PIPE)
                .setValue(ItemPipeBlock.SOUTH, LinkSide.PIPE);
    }
}
